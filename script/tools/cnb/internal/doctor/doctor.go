// Package doctor 检查构建前置条件：容器运行时、API socket、builder 契约。
package doctor

import (
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"slices"
	"strings"
	"time"

	"learn-cnb-paketo/tools/cnb/internal/buildmeta"
	"learn-cnb-paketo/tools/cnb/internal/profile"
)

// 检查项常量。
const (
	stageKindImage = "image"
	stageRun       = "run"
	stageBuilder   = "builder"

	inspectTimeout = 5 * time.Second

	envUserID  = "CNB_USER_ID="
	envGroupID = "CNB_GROUP_ID="
	labelStack = "io.buildpacks.stack.id"
	labelRun   = "runImage"

	baseImageKey    = "BASE_IMAGE"
	baseImageTagKey = "BASE_IMAGE_TAG"
)

// glibcBuildpacks 是需要 glibc run 镜像的组件。
var glibcBuildpacks = map[string]bool{
	"node-engine": true,
	"npm-start":   true,
	"cpython":     true,
	"pip-install": true,
}

// Level 是检查结论。
type Level int

const (
	// LevelOK 通过。
	LevelOK Level = iota
	// LevelFail 不达标。
	LevelFail
	// LevelSkip 跳过。
	LevelSkip
)

// Item 是一条检查结果。
type Item struct {
	Level Level
	Title string
	Hint  string
}

// Report 是一次体检结果。
type Report struct {
	Items []Item
}

// Problems 返回不达标项数量。
func (r Report) Problems() int {
	n := 0
	for _, it := range r.Items {
		if it.Level == LevelFail {
			n++
		}
	}
	return n
}

// OK 判断是否全部通过（跳过不计）。
func (r Report) OK() bool { return r.Problems() == 0 }

// Run 执行全部检查。
func Run(plan *profile.Plan) Report {
	var rep Report
	add := func(level Level, title, hint string) {
		rep.Items = append(rep.Items, Item{Level: level, Title: title, Hint: hint})
	}

	add(Kind(plan.Runtime != "none"), "container runtime: "+plan.Runtime, "install podman or docker")
	if plan.Runtime == "podman" {
		sock := podmanSocket()
		_, err := os.Stat(sock)
		add(Kind(err == nil), "podman API socket: "+sock,
			"systemctl --user enable --now podman.socket")
	}
	checkBuilder(plan, add)
	checkRunLibc(plan, add)

	if _, err := buildmeta.Generate(plan); err != nil {
		add(LevelFail, "generate builder metadata", err.Error())
	} else {
		add(LevelOK, "generate builder metadata", "")
	}
	return rep
}

// Kind 把布尔值转换为检查结论。
func Kind(ok bool) Level {
	if ok {
		return LevelOK
	}
	return LevelFail
}

// checkBuilder 检查 builder 镜像的环境变量与标签。
func checkBuilder(plan *profile.Plan, add func(Level, string, string)) {
	tag := ""
	for _, st := range plan.Stages {
		if st.Kind == stageKindImage && strings.Contains(st.Name, stageBuilder) {
			tag = st.Tag
		}
	}
	if tag == "" || plan.Runtime == "none" {
		return
	}
	env := inspect(plan.Runtime, tag, "{{range .Config.Env}}{{println .}}{{end}}")
	add(Kind(strings.Contains(env, envUserID)), "builder env CNB_USER_ID",
		"add ENV CNB_USER_ID=1000 to the builder Dockerfile")
	add(Kind(strings.Contains(env, envGroupID)), "builder env CNB_GROUP_ID",
		"add ENV CNB_GROUP_ID=1000 to the builder Dockerfile")

	labels := inspect(plan.Runtime, tag, "{{json .Config.Labels}}")
	add(Kind(strings.Contains(labels, labelStack)), "builder label stack.id",
		"cnb run injects it automatically")
	add(Kind(strings.Contains(labels, labelRun)), "builder metadata contains runImage",
		"ensure metadata is generated by cnb")
}

// checkRunLibc 检查 run 镜像 libc 与运行时是否匹配。
func checkRunLibc(plan *profile.Plan, add func(Level, string, string)) {
	base := ""
	for _, st := range plan.Stages {
		if st.Kind == stageKindImage && st.Name == stageRun {
			base = firstNonEmpty(st.Args[baseImageKey], st.Args[baseImageTagKey])
		}
	}
	if base == "" {
		add(LevelSkip, "run image declares no BASE_IMAGE; libc check skipped", "")
		return
	}
	if isMusl(base) && needsGlibc(plan) {
		add(LevelFail, "run image is musl ("+base+") but project has Node/Python workloads",
			"use a debian/ubuntu base image; glibc binaries fail with ENOENT under musl")
		return
	}
	add(LevelOK, "run image libc matches runtime", "")
}

// needsGlibc 判断项目是否包含需要 glibc 的运行时。
func needsGlibc(plan *profile.Plan) bool {
	if slices.Contains(plan.Assets, "fnm") || slices.Contains(plan.Assets, "uv") {
		return true
	}
	entries, err := os.ReadDir(plan.BuildpacksDir)
	if err != nil {
		return false
	}
	for _, e := range entries {
		if glibcBuildpacks[e.Name()] {
			return true
		}
	}
	return false
}

// isMusl 判断基础镜像是否为 musl 系。
func isMusl(base string) bool {
	lower := strings.ToLower(base)
	return strings.Contains(lower, "alpine") || strings.Contains(lower, "musl")
}

// podmanSocket 返回 rootless podman 的 API socket 路径。
func podmanSocket() string {
	if dir := os.Getenv("XDG_RUNTIME_DIR"); dir != "" {
		return filepath.Join(dir, "podman", "podman.sock")
	}
	return fmt.Sprintf("/run/user/%d/podman/podman.sock", os.Getuid())
}

// inspect 读取镜像字段，超时返回空串。
func inspect(tool, image, format string) string {
	cmd := exec.Command(tool, "inspect", "--format", format, image)
	done := make(chan struct{})
	var out []byte
	var err error
	go func() {
		out, err = cmd.Output()
		close(done)
	}()
	select {
	case <-done:
		if err != nil {
			return ""
		}
		return string(out)
	case <-time.After(inspectTimeout):
		_ = cmd.Process.Kill()
		return ""
	}
}

func firstNonEmpty(values ...string) string {
	for _, v := range values {
		if v != "" {
			return v
		}
	}
	return ""
}
